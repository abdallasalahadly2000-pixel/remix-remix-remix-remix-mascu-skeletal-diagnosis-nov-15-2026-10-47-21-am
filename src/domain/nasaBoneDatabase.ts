export function deriveSeverityFromBone(bone: BoneSegment): SeverityLevelId {
  if (bone.zScore !== null && !Number.isNaN(bone.zScore)) {
    if (bone.zScore >= -1.0) return 'L1';
    if (bone.zScore > -1.75) return 'L2';
    if (bone.zScore > -2.5) return 'L3';
    return 'L4';
  }
  if (bone.weaknessPercent !== null && !Number.isNaN(bone.weaknessPercent)) {
    if (bone.weaknessPercent < 18) return 'L1';
    if (bone.weaknessPercent < 38) return 'L2';
    if (bone.weaknessPercent < 55) return 'L3';
    return 'L4';
  }
  return 'L1';
}

